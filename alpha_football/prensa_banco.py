from __future__ import annotations

_TONOS = {'m': 'motivador', 'p': 'provocador', 'h': 'humilde', 'a': 'agresivo',
          'i': 'ironico', 'd': 'diplomatico', 'e': 'elogioso', 's': 'evasivo'}


def _q(texto: str, **respuestas: str) -> dict:
    """Una pregunta con sus respuestas; la clave es la inicial del tono (m, p, h, a, i, d, e, s)."""
    return {'texto': texto, 'respuestas': {_TONOS[k]: v for k, v in respuestas.items()}}


