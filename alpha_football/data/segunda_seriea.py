def _construir_equipo(nombre: str, datos: dict, id_base: int) -> Equipo:
    jugadores = []
    for idx, (nom, ape, pos, ovr, rasgo, edad) in enumerate(datos["jugadores"]):
        ataque, defensa, fisico, tecnica, mental = generar_atributos_por_posicion(ovr, pos)
        jugadores.append(Jugador(
            nombre=nom,
            apellido=ape,
            posicion=pos,
            ataque=ataque,
            defensa=defensa,
            fisico=fisico,
            tecnica=tecnica,
            mental=mental,
            moral=70,
            rasgo=rasgo,
            id=id_base + idx,
            edad=edad,
        ))
    return Equipo(
        nombre=nombre,
        ciudad=datos["ciudad"],
        estrellas=datos["estrellas"],
        estilo_dt=datos["estilo_dt"],
        balance=datos["balance"],
        jugadores=jugadores,
        es_usuario=False,
        nombre_corto=nombre[:14],
        division=2,
    )


def get_liga() -> Liga:
    try:
        equipos = []
        id_base = 36000   # v3.7.0: rango propio de la Serie B
        for nombre, datos in PLANTILLAS_2A.items():
            equipos.append(_construir_equipo(nombre, datos, id_base))
            id_base += 100
        liga = Liga(
            nombre="Serie B Parodia",
            tipo="seriea",
            equipos=equipos,
            num_jornadas=max(2, 2 * (len(equipos) - 1)),  # v3.7.0: ida y vuelta (12 → 22)
            division=2,
            jornada_actual=1,
        )
        logger.info(f"2ª división Italia cargada: {len(equipos)} equipos, "
                    f"{sum(len(e.jugadores) for e in equipos)} jugadores totales")
        return liga
    except Exception as e:
        logger.error(f"Error al construir 2ª división Italia: {e}")
        return Liga(nombre="Serie B Parodia (error)", tipo="seriea", equipos=[], num_jornadas=2, division=2)
